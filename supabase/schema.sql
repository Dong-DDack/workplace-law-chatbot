create extension if not exists vector with schema extensions;

create table if not exists public.law_documents (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  title text not null,
  effective_date date,
  source_file text not null,
  source_url text,
  created_at timestamptz not null default now()
);

create table if not exists public.law_chunks (
  id bigint generated by default as identity primary key,
  document_id bigint not null references public.law_documents(id) on delete cascade,
  chunk_index integer not null,
  article_number text,
  part_number integer not null default 1,
  pages integer[] not null default '{}',
  content text not null,
  embedding extensions.vector(768) not null,
  embedding_model text not null,
  created_at timestamptz not null default now(),
  constraint law_chunks_document_chunk_unique unique (document_id, chunk_index)
);

create index if not exists law_chunks_embedding_hnsw_idx
  on public.law_chunks using hnsw (embedding extensions.vector_cosine_ops);

alter table public.law_documents enable row level security;
alter table public.law_chunks enable row level security;

grant usage on schema public to service_role;
grant usage on schema extensions to service_role;
grant select, insert, update, delete on public.law_documents, public.law_chunks to service_role;
grant usage, select on all sequences in schema public to service_role;

create or replace function public.match_law_chunks(
  query_embedding extensions.vector(768),
  match_threshold real,
  match_count integer
)
returns table (
  id bigint,
  document_id bigint,
  chunk_index integer,
  article_number text,
  pages integer[],
  content text,
  similarity real
)
language sql
stable
set search_path = public, extensions
as $$
  select
    chunk.id,
    chunk.document_id,
    chunk.chunk_index,
    chunk.article_number,
    chunk.pages,
    chunk.content,
    (1 - (chunk.embedding <=> query_embedding))::real as similarity
  from public.law_chunks as chunk
  where 1 - (chunk.embedding <=> query_embedding) >= match_threshold
  order by chunk.embedding <=> query_embedding
  limit greatest(match_count, 0);
$$;

grant execute on function public.match_law_chunks(extensions.vector, real, integer) to service_role;
